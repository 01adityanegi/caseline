import { NextRequest, NextResponse } from 'next/server'
import { auth } from '@/lib/auth'
import { prisma } from '@/lib/db'

export async function POST(req: NextRequest) {
  try {
    const session = await auth()
    if (!session?.user) {
      return NextResponse.json({ error: 'Authentication required' }, { status: 401 })
    }

    const body = await req.json()
    const { template } = body

    if (!template || !template.suggestedTitle) {
      return NextResponse.json({ error: 'Template data is required' }, { status: 400 })
    }

    const code = `CUSTOM_${Date.now()}_${Math.random().toString(36).substring(2, 6).toUpperCase()}`

    const saved = await prisma.agreementTemplate.create({
      data: {
        code,
        category: template.category || 'Business & Work',
        titleEn: template.suggestedTitle,
        titleHi: template.suggestedTitleHi || template.suggestedTitle,
        descriptionEn: template.description || 'Custom agreement template generated by CaseLine AI Inspector',
        descriptionHi: template.descriptionHi || 'केसलाइन एआई द्वारा परीक्षित एवं जनरेटेड कस्टम अनुबंध टेम्पलेट',
        iconName: 'FileCheck',
        estimatedMinutes: 5,
        languages: JSON.stringify(['EN', 'HI']),
        formSchema: JSON.stringify(template.placeholders || []),
        clausesSchema: JSON.stringify(template.clauses || []),
      },
    })

    return NextResponse.json({
      success: true,
      templateCode: saved.code,
      id: saved.id,
      title: saved.titleEn,
      message: 'Agreement successfully saved as a reusable template!'
    })
  } catch (error: any) {
    console.error('Error saving inspected agreement template:', error)
    return NextResponse.json(
      { error: error?.message || 'Failed to save agreement template' },
      { status: 500 }
    )
  }
}

